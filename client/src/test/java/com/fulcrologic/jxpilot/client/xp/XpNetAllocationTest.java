package com.fulcrologic.jxpilot.client.xp;

import com.fulcrologic.jxpilot.client.game.ClientGame;
import com.fulcrologic.jxpilot.client.net.ConnectionState;
import com.fulcrologic.jxpilot.client.net.Transport;
import com.fulcrologic.jxpilot.common.net.ControlKey;
import org.junit.jupiter.api.Test;

import java.lang.management.ManagementFactory;
import java.nio.ByteBuffer;
import java.util.ArrayList;
import java.util.List;

import static org.junit.jupiter.api.Assertions.*;

/**
 * Steady-state play on a C server allocates nothing: receiving and decoding C frames (ships, debris,
 * fast shots, radar, map updates) and reliable data (messages, scores, talk acks), translating them into
 * snapshots, ClientGame ingest and interpolation, keyboard changes and resends, map-object acks and chat.
 * <p>
 * The handshake runs against {@link FakeCServer}; the steady-state datagrams are generated by the same
 * server beforehand and replayed allocation-free. Each client frame is measured on its own after
 * {@value #WARMUP} warm-up frames: at most {@value #MAX_NONZERO_FRAMES} frames may allocate (at most
 * {@value #MAX_FRAME_BYTES} bytes each: the JIT occasionally allocates on the running thread when it
 * installs code) and none in the second half, so a periodic leak fails. The longest possible message is
 * sent during warm-up, since message buffers grow once to their final size. Runs in its own surefire
 * execution with escape analysis off (pom: *NetAllocationTest).
 */
class XpNetAllocationTest {
    static final int WARMUP = 30_000;
    static final int MEASURED = 30_000;
    static final int MAX_NONZERO_FRAMES = 3;
    static final long MAX_FRAME_BYTES = 1024;
    /** Client frames per C frame (60 Hz client, 12 fps server). */
    static final int RATIO = 5;

    /** Delegates to a replaceable transport (handshake over the fake server, steady state over a ring). */
    static final class Switch implements Transport {
        Transport target;

        @Override
        public boolean send(ByteBuffer p) throws java.io.IOException {
            return target.send(p);
        }

        @Override
        public int receive(ByteBuffer b) throws java.io.IOException {
            return target.receive(b);
        }

        @Override
        public void close() {
        }
    }

    /** Preloaded datagrams delivered by client frame; sends are swallowed. Allocation free. */
    static final class Ring implements Transport {
        final byte[][] packets;
        final int[] due;
        int next;
        int frame;

        Ring(List<byte[]> ps, List<Integer> dueFrames) {
            packets = ps.toArray(new byte[0][]);
            due = new int[packets.length];
            for (int i = 0; i < due.length; i++) {
                due[i] = dueFrames.get(i);
            }
        }

        @Override
        public boolean send(ByteBuffer p) {
            p.position(p.limit());
            return true;
        }

        @Override
        public int receive(ByteBuffer b) {
            if (next >= packets.length || due[next] > frame) {
                return 0;
            }
            b.put(packets[next]);
            return packets[next++].length;
        }

        @Override
        public void close() {
        }
    }

    @Test
    void steadyStatePlayOnACServerAllocatesNothing() {
        com.sun.management.ThreadMXBean mx = (com.sun.management.ThreadMXBean) ManagementFactory.getThreadMXBean();
        FakeCServer server = new FakeCServer();
        Switch sw = new Switch();
        XpConnection.PortOpener opener = port -> {
            Transport t = server.open(port);
            if (port == FakeCServer.LOGIN_PORT) {
                sw.target = t;
                return sw;
            }
            return t;
        };
        ClientGame game = new ClientGame();
        XpConnection conn = new XpConnection(opener, game, "fake:15345", new XpConnection.Login());
        long frameNs = 1_000_000_000L / 60;
        long now = 1_000_000_000L;
        conn.start(now);
        server.step();
        for (int i = 0; i < 400 && conn.snapshotsReceived() < 20; i++) {
            now += frameNs;
            conn.update(now);
            game.frame(now, frameNs / 1e9);
            conn.sendInput(0, 0, now);
            conn.flush(now);
            server.step();
        }
        assertEquals(ConnectionState.PLAYING, conn.state(), "joined during setup");

        // C frames with reliable traffic: a chat echo with its talk ack, a score change and a game message
        // every 60 C frames.
        server.login.toClient.clear();
        server.retransmitSteps = 3;
        List<byte[]> packets = new ArrayList<>();
        List<Integer> due = new ArrayList<>();
        int cFrames = (WARMUP + MEASURED) / RATIO + 20;
        for (int f = 0; f < cFrames; f++) {
            if (f == 10) {
                server.stream.put(new CPackets().message("m".repeat(XpProto.MSG_LEN - 1)).bytes());
            }
            if (f % 60 == 30) {
                server.stream.put(new CPackets().talkAck(f).message("chat " + f + " [Robby]")
                    .score(FakeCServer.ROBOT_ID, f / 10.0, 0, 'R', ' ').message("Robby was killed.").bytes());
            }
            server.step();
            for (byte[] a = server.login.toClient.poll(); a != null; a = server.login.toClient.poll()) {
                packets.add(a);
                due.add(RATIO * f);
            }
        }
        Ring ring = new Ring(packets, due);
        sw.target = ring;
        long[] t = {now};
        long thrust = ControlKey.THRUST.mask();
        long left = ControlKey.TURN_LEFT.mask();
        Runnable frame = () -> {
            t[0] += frameNs;
            int fr = ring.frame;
            long keys = fr % 40 < 20 ? thrust : thrust | left;
            conn.update(t[0]);
            game.frame(t[0], frameNs / 1e9);
            conn.sendInput(keys, 0, t[0]);
            if (fr % 300 == 150) {
                conn.sendChat("hello robots", t[0]);
            }
            conn.flush(t[0]);
            ring.frame++;
        };
        for (int i = 0; i < WARMUP; i++) {
            frame.run();
        }
        int nonZero = 0;
        long worst = 0;
        int lastNonZero = -1;
        for (int i = 0; i < MEASURED; i++) {
            long before = mx.getCurrentThreadAllocatedBytes();
            frame.run();
            long bytes = mx.getCurrentThreadAllocatedBytes() - before;
            if (bytes > 0) {
                nonZero++;
                worst = Math.max(worst, bytes);
                lastNonZero = i;
            }
        }
        int nz = nonZero;
        long w = worst;
        int last = lastNonZero;
        assertAll(
            () -> assertEquals(ConnectionState.PLAYING, conn.state(), "still playing"),
            () -> assertTrue(conn.snapshotsReceived() > (WARMUP + MEASURED) / RATIO - 10,
                "C frames flowed: " + conn.snapshotsReceived()),
            () -> assertEquals(0, conn.malformed(), "nothing malformed"),
            () -> assertTrue(game.world().pointCount() > 0, "debris tracked as point particles"),
            () -> assertTrue(game.messages().talkCount() > 0, "chat arrived"),
            () -> assertTrue(conn.keyboard().change() > 100, "keys changed"),
            () -> assertTrue(nz <= MAX_NONZERO_FRAMES, "at most a few JIT frames allocate: " + nz),
            () -> assertTrue(w <= MAX_FRAME_BYTES, "and only a little: " + w + " bytes"),
            () -> assertTrue(last < MEASURED / 2, "nothing allocates in the second half (last at " + last + ")"));
    }
}
